def test_an_unhashable_field_reference_raises_a_spec_error_not_a_typeerror(csv_file, out_dir):
    """``{"field": {...}}`` reached ``ref.field in field_map`` and raised TypeError.

    An internal error tells the caller nothing about which key to fix.
    """
    spec = make_spec(csv_file, out_dir)
    spec["worksheets"][0]["rows"] = [{"field": {"a": 1}}]
    with pytest.raises(SpecError, match="must be a non-empty field-name string"):
        parse_spec(spec)
