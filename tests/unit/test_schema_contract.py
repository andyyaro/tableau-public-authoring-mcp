def test_every_object_in_the_schema_rejects_unknown_properties():
    """The contract's headline promise: "unknown properties are rejected everywhere".

    Checked structurally rather than per-node, so a subschema added later inherits
    the guarantee instead of silently opting out of it.
    """
    for path, node in _walk(spec_json_schema()):
        if node.get("type") == "object" or "required" in node:
            assert node.get("additionalProperties") is False, (
                f"{path} accepts unknown properties; parse_spec rejects them"
            )


