"""Guards against the published contract disagreeing with the enforced one.

Sibling of test_capability_drift.py, written for the same class of defect. That
module exists because ``get_authoring_capabilities`` reported dashboards as
unsupported for weeks after they worked. This one exists because
``schemas/workbook-spec-v0.1.json`` -- advertised in the README, in
docs/AUTHORING_SPEC.md and in the ``author_workbook`` tool description as the
machine-readable contract -- was never loaded by anything, and so had quietly
drifted: it set ``additionalProperties: false`` on worksheets while omitting
``fit``, a key ``parse_spec`` accepts, the compiler emits, and
docs/architecture/CAPABILITY_BOUNDARY.md lists as verified end-to-end. A consumer
validating against the published contract rejected a spec the server built and
published successfully.

A stale schema is worse than no schema. No schema makes a caller read the docs; a
wrong one makes a caller confidently reject valid work, or -- in the other
direction -- send a document the server will reject after the caller's own
validation said it was fine.

The fix was to stop maintaining two descriptions of the same thing. The schema is
now GENERATED by ``spec_json_schema()`` from the constants and dataclasses
``parse_spec`` itself uses, and the checked-in JSON file is that function's
output. These tests pin all three relationships:

1. the published file IS what the generator emits (no hand-edits survive);
2. every key set, enum, pattern and bound in it is derived from the model, not
   restated -- adding a field to :class:`Worksheet` fails this file until the
   generator knows about it;
3. the schema never rejects a spec ``parse_spec`` accepts, and still rejects the
   structural mistakes ``parse_spec`` rejects -- so nobody can make (1) and (2)
   pass by hollowing the schema out.
"""

