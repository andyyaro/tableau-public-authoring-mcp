# The exact serialisation the published file must have. Pinned so a regeneration
# produces a clean diff instead of a whole-file reflow.
SCHEMA_JSON_INDENT = 2


def _published_text() -> str:
    return json.dumps(spec_json_schema(), indent=SCHEMA_JSON_INDENT) + "\n"


def _validator() -> Draft202012Validator:
    return Draft202012Validator(spec_json_schema())


def _worksheet_props() -> dict:
    return spec_json_schema()["properties"]["worksheets"]["items"]["properties"]


def _dashboard_props() -> dict:
    return spec_json_schema()["properties"]["dashboards"]["items"]["properties"]


def _default_of(cls, field_name: str):
    """The dataclass default the generator's ``default`` keyword must agree with."""
    for f in dataclass_fields(cls):
        if f.name == field_name:
            assert f.default is not MISSING, f"{cls.__name__}.{field_name} has no plain default"
            return f.default
    raise AssertionError(f"{cls.__name__} has no field {field_name!r}")


def _walk(node, path="$"):
    """Yield (json-pointer-ish path, subschema) for every object subschema."""
    if isinstance(node, dict):
        yield path, node
        for key, value in node.items():
            yield from _walk(value, f"{path}.{key}")
    elif isinstance(node, list):
        for i, value in enumerate(node):
            yield from _walk(value, f"{path}[{i}]")


