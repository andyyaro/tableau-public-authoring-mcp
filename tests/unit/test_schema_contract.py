def test_every_enum_comes_from_the_model():
    """No enum in the contract may be a typed-out copy of a tuple in spec.py.

    ``fit`` carries a trailing null because parse_spec treats an explicit null as
    "not set", and a contract that omitted it would reject a working spec.
    """
    schema = spec_json_schema()
    worksheet = _worksheet_props()
    dashboard = _dashboard_props()
    assert worksheet["template"]["enum"] == list(SUPPORTED_TEMPLATES)
    assert worksheet["fit"]["enum"] == [*FIT_MODES, None]
    assert schema["$defs"]["aggregation"]["enum"] == list(AGGREGATIONS)
    assert schema["$defs"]["datatype"]["enum"] == list(VALID_DATATYPES)
    assert dashboard["direction"]["enum"] == list(DASHBOARD_DIRECTIONS)
    assert dashboard["sizing_mode"]["enum"] == list(DASHBOARD_SIZING_MODES)


def test_patterns_and_bounds_come_from_the_model():
    schema = spec_json_schema()
    assert schema["$defs"]["displayName"]["pattern"] == NAME_PATTERN_JSON
    assert schema["properties"]["spec_version"]["const"] == SPEC_VERSION

    dash = _dashboard_props()
    assert dash["title"]["maxLength"] == DASHBOARD_TITLE_MAX
    assert dash["worksheets"]["maxItems"] == DASHBOARD_MAX_ZONES
    for axis in ("width", "height"):
        assert dash[axis]["minimum"] == DASHBOARD_MIN_PX
        assert dash[axis]["maximum"] == DASHBOARD_MAX_PX
    assert dash["width"]["default"] == DASHBOARD_DEFAULT_WIDTH
    assert dash["height"]["default"] == DASHBOARD_DEFAULT_HEIGHT


